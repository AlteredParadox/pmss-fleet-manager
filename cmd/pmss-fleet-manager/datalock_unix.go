package main

import (
	"errors"
	"os"
	"path/filepath"
	"syscall"
)

// lockDataDir takes an exclusive lock on the data directory for the life
// of the process: the server holds it while it runs, and restore takes it
// so it cannot replace the database under a running dashboard. The lock
// is the kernel's (flock), so it goes with the process however it ends;
// the file itself stays and means nothing on its own.
func lockDataDir(dir string) (release func(), err error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, err
	}
	f, err := os.OpenFile(filepath.Join(dir, lockName), os.O_CREATE|os.O_RDWR, 0o600)
	if err != nil {
		return nil, err
	}
	if err := syscall.Flock(int(f.Fd()), syscall.LOCK_EX|syscall.LOCK_NB); err != nil {
		f.Close()
		if errors.Is(err, syscall.EWOULDBLOCK) {
			return nil, errDataDirInUse
		}
		return nil, err
	}
	return func() { f.Close() }, nil
}
